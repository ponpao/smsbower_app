_current = "km"  # app default language, as in v1.0.1


def set_language(code: str) -> None:
    global _current
    if code in TRANSLATIONS:
        _current = code


def current_language() -> str:
    return _current


def tr(key: str, **kwargs) -> str:
    text = TRANSLATIONS.get(_current, _EN).get(key) or _EN.get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text


def missing_keys() -> dict:
    """Sanity helper: report keys missing from any non-English language."""
    ref = set(_EN)
    return {code: sorted(ref - set(d)) for code, d in TRANSLATIONS.items() if set(d) != ref}
